const dialog = (page, name) => page.getByRole('dialog', { name, exact: true });
const submit = async (drawer) => { await drawer.getByRole('button', { name: 'Ghi nhận', exact: true }).click(); await expect(drawer).toBeHidden(); };
const timezoneValue = (drawer, label) => drawer.locator('.ant-form-item').filter({ hasText: label }).locator('.ant-select-selection-item');
async function select(drawer, label, name) {
    await drawer.getByLabel(label, { exact: true }).focus();
    await drawer.getByLabel(label, { exact: true }).fill(name);
    await drawer.getByLabel(label, { exact: true }).press('ArrowDown');
    await drawer.page().locator('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option-content').filter({ hasText: name }).first().click();
}

async function selectTime(modal, label, time) {
    const input = modal.getByLabel(label, { exact: true });
    await expect(input).toHaveAttribute('readonly', '');
    await input.click();
    const popup = modal.page().locator('.ant-picker-dropdown:not(.ant-picker-dropdown-hidden)');
    await expect(popup).toBeVisible();
    const [hour, minute] = time.split(':');
    await popup.locator('.ant-picker-time-panel-column').nth(0).getByText(hour, { exact: true }).click();
    await popup.locator('.ant-picker-time-panel-column').nth(1).getByText(minute, { exact: true }).click();
    await modal.getByLabel('Mã ca', { exact: true }).click();
    await expect(popup).toBeHidden();
    await expect(input).toHaveValue(time);
}

