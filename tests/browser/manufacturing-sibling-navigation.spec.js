import { expect, test } from '@playwright/test';

test.skip(process.env.PLAYWRIGHT_MANUFACTURING_FIXTURE !== '1', 'Chỉ dùng fixture Manufacturing cô lập.');

test('sibling links follow the active group and stay accessible on mobile', async ({ page }) => {
    expect(['localhost', '127.0.0.1']).toContain(new URL(test.info().project.use.baseURL).hostname);
    expect(process.env.MANUFACTURING_BROWSER_SECRET?.length).toBeGreaterThanOrEqual(32);
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.setViewportSize({ width: 1047, height: 853 });
    await page.goto(`/__manufacturing_fixture/login/${process.env.MANUFACTURING_BROWSER_SECRET}`);
    await page.goto('/admin/modules/manufacturing/materials');
    const production = page.getByRole('navigation', { name: 'Chức năng Sản xuất', exact: true });
    await expect(production.getByRole('link')).toHaveCount(5);
    await expect(production.getByRole('link', { name: 'Nguyên liệu', exact: true })).toHaveAttribute('aria-current', 'page');
    const mainMenu = page.locator('.admin-sub-header');
    expect((await production.boundingBox()).y).toBeGreaterThanOrEqual((await mainMenu.boundingBox()).y + (await mainMenu.boundingBox()).height);
    await page.screenshot({ path: test.info().outputPath('siblings-desktop.png'), animations: 'disabled' });
    await production.getByRole('link', { name: 'Cắt và bó', exact: true }).click();
    await expect(page).toHaveURL(/\/manufacturing\/cutting$/);
    await expect(production.getByRole('link', { name: 'Cắt và bó', exact: true })).toHaveAttribute('aria-current', 'page');
    await expect(production.locator('[aria-current="page"]')).toHaveCount(1);
    await page.goto('/admin/modules/manufacturing/demands');
    const preparation = page.getByRole('navigation', { name: 'Chức năng Chuẩn bị', exact: true });
    await expect(preparation.getByRole('link')).toHaveCount(3);
    await expect(production).toBeHidden();
    await preparation.getByRole('link', { name: 'Kế hoạch', exact: true }).click();
    await expect(page).toHaveURL(/\/manufacturing\/planning$/);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/admin/modules/manufacturing/subcontracts');
    const current = production.getByRole('link', { name: 'Gia công ngoài', exact: true });
    await expect(current).toHaveAttribute('aria-current', 'page');
    await expect(current).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath('siblings-mobile.png'), animations: 'disabled' });
    await production.evaluate((node) => { node.scrollLeft = 0; });
    await production.getByRole('link', { name: 'Nguyên liệu', exact: true }).click();
    await expect(page).toHaveURL(/\/manufacturing\/materials$/);
    await expect(production.getByRole('link', { name: 'Nguyên liệu', exact: true })).toBeInViewport();
    await page.goto('/admin/modules/manufacturing/settings');
    await expect(page.locator('.admin-manufacturing-subnav')).toHaveCount(0);
    await page.goto('/admin/modules/manufacturing/fulfillment');
    const finished = page.getByRole('navigation', { name: 'Chức năng Thành phẩm', exact: true });
    await expect(finished.getByRole('link')).toHaveCount(2);
    await finished.getByRole('link', { name: 'Giá thành', exact: true }).click();
    await expect(page).toHaveURL(/\/manufacturing\/costing$/);
    await expect(finished.getByRole('link', { name: 'Giá thành', exact: true })).toHaveAttribute('aria-current', 'page');
    expect(errors).toEqual([]);
});
