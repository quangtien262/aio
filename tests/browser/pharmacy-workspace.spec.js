test('synthetic UI: internal mappings preserve accounting and customer authority scopes', async ({ page }) => {
    await page.goto('/admin/modules/pharmacy/integrations');
    await page.getByRole('button', { name: 'Thêm ánh xạ pháp nhân' }).click();
    const organization = page.getByRole('combobox', { name: /Pháp nhân kế toán được ủy quyền/ });
    await organization.focus(); await organization.press('ArrowDown');
    await page.getByText('Pháp nhân mẫu', { exact: true }).last().click();
    const product = page.getByRole('combobox', { name: 'Hàng ánh xạ 1' });
    await product.focus(); await product.press('ArrowDown');
    await page.getByText('TEST-A · Hàng thử nghiệm A', { exact: true }).last().click();
    const item = page.getByRole('combobox', { name: 'Hàng kế toán 1' });
    await item.focus(); await item.press('ArrowDown');
    await page.getByText('Hàng kế toán A', { exact: true }).last().click();
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByRole('button', { name: 'Lưu và xác nhận' })).toHaveCount(0);
    const mapping = await page.evaluate(() => window.__lastPharmacyCommand);
    expect(mapping.action).toBe('accounting.mapping.save');
    expect(mapping.organization_id).toBe(11);
    expect(mapping.item_mappings).toEqual([{ product_id: 'product-a', accounting_item_id: 17 }]);
    expect(mapping).not.toHaveProperty('website_key');
    await page.getByRole('button', { name: 'Cấu hình ủy quyền nhóm' }).click();
    const book = page.getByRole('combobox', { name: /Nhóm khách hàng được ủy quyền/ });
    await book.focus(); await book.press('ArrowDown');
    await page.getByText('Nhóm thương mại mẫu', { exact: true }).last().click();
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByRole('button', { name: 'Lưu và xác nhận' })).toHaveCount(0);
    const customer = await page.evaluate(() => window.__lastPharmacyCommand);
    expect(customer).toMatchObject({ action: 'customer.mapping.save', pharmacy_id: 'pharmacy-a', book_id: 'book-a', website_key: 'commercial-scope' });
    expect(customer).not.toHaveProperty('clinical_sharing');
});

test('synthetic UI: editing catalog keeps each ingredient strength and unit intact', async ({ page }) => {
    await page.goto('/admin/modules/pharmacy/products');
    await page.getByRole('row').filter({ hasText: 'TEST-A' }).getByRole('button', { name: 'Sửa', exact: true }).click();
    await expect(page.getByRole('textbox', { name: /Tên hoạt chất/ }).first()).toHaveValue('Thành phần mẫu A');
    await page.getByRole('textbox', { name: /Tên thuốc \/ hàng hóa/ }).fill('Tên hàng đã đối chiếu');
    await page.getByRole('button', { name: 'Lưu thay đổi' }).click();
    await expect(page.getByRole('button', { name: 'Lưu thay đổi' })).toHaveCount(0);
    const payload = await page.evaluate(() => window.__lastPharmacyCommand);
    expect(payload.action).toBe('product.save');
    expect(payload.ingredients).toEqual([{ name: 'Thành phần mẫu A', strength: '10', unit: 'mg' }, { name: 'Thành phần mẫu B', strength: '20', unit: 'mg' }]);
});
