import { test, expect } from '@playwright/test';

test('synthetic UI: keyboard search, server draft, exact-lot preparation and separated states', async ({ page }) => {
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto('/admin/modules/pharmacy/pos');
    await expect(page.getByRole('heading', { name: 'Quầy thuốc', exact: true })).toBeVisible();
    await page.keyboard.press('F2');
    await expect(page.getByRole('searchbox', { name: 'Quét hoặc tìm hàng hóa' })).toBeFocused();
    await page.getByRole('button', { name: /TEST-A Hàng thử nghiệm A/ }).click();
    await page.getByRole('button', { name: 'Lưu hồ sơ & chuẩn bị hàng' }).click();
    await expect(page).toHaveURL(/dispensings\/dispensing-demo/);
    await expect(page.getByText('Chưa thu tiền', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '1. Chuẩn bị hàng & lô' }).click();
    await page.getByRole('combobox', { name: 'Lô thực lấy 1' }).focus();
    await page.getByRole('combobox', { name: 'Lô thực lấy 1' }).press('ArrowDown');
    await page.getByText(/LOT-DEMO/).click();
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByRole('button', { name: '2. Kiểm tra chuyên môn' })).toBeEnabled();
    const payload = await page.evaluate(() => window.__lastPharmacyCommand);
    expect(payload.allocations).toEqual([{ line_id: 'line-0', batch_id: '7', quantity: '1' }]);
    expect(payload.expected_version).toBe(1);
    expect(payload.pharmacy_id).toBe('pharmacy-a');
    expect(payload).not.toHaveProperty('website_key');
    await page.getByRole('button', { name: '2. Kiểm tra chuyên môn' }).click();
    await page.getByRole('combobox', { name: 'Kết quả' }).focus();
    await page.getByRole('combobox', { name: 'Kết quả' }).press('ArrowDown');
    await page.getByText('Đã kiểm tra — đồng ý', { exact: true }).click();
    await page.getByRole('textbox', { name: 'Căn cứ kiểm tra' }).fill('Đối chiếu dữ liệu tổng hợp fixture');
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await page.getByRole('button', { name: '3. Thu tiền & chốt' }).click();
    await page.getByRole('combobox', { name: 'Ca thu tiền' }).focus();
    await page.getByRole('combobox', { name: 'Ca thu tiền' }).press('ArrowDown');
    await page.getByText('Ca mô phỏng', { exact: true }).click();
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByText('Đã thu tiền', { exact: true })).toBeVisible();
    await expect(page.getByText('Chờ xử lý', { exact: true }).first()).toBeVisible();
    await page.getByRole('button', { name: '4. Bàn giao' }).click();
    await page.getByRole('textbox', { name: /Người nhận/ }).fill('Người nhận fixture');
    await page.getByRole('textbox', { name: 'Ghi nhận bàn giao' }).fill('Đã đối chiếu bộ dữ liệu thử nghiệm');
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByText('Đã bàn giao', { exact: true }).first()).toBeVisible();
    const stored = await page.evaluate(() => JSON.stringify(localStorage));
    expect(stored).not.toContain('Người nhận fixture');
    expect(errors).toEqual([]);
});
