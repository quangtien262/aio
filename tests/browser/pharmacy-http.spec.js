import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('isolated PHP: native workflow, mobile/context privacy and report-only access', async ({ page, browser }, testInfo) => {
    const path = process.env.PHARMACY_HTTP_FIXTURE;
    if (!path?.startsWith('/private/tmp/aio-pharmacy-http-')) throw new Error('Generate an isolated Pharmacy HTTP fixture first.');
    const fixture = JSON.parse(await readFile(path, 'utf8'));
    if (fixture.environment.APP_ENV !== 'testing' || fixture.environment.DB_CONNECTION !== 'sqlite') throw new Error('Only the dedicated test installation is authorized.');
    const errors = [];
    const websiteHeaders = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('request', (request) => { if (request.url().includes('/admin/api/pharmacy/')) websiteHeaders.push(request.headers()['x-website-key']); });
    await page.goto('/admin/pharmacy/login');
    await page.getByLabel('Tên đăng nhập hoặc email').fill(fixture.username);
    await page.getByLabel('Mật khẩu', { exact: true }).fill(fixture.password);
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/modules\/pharmacy/);
    await expect(page.getByText('Bắt đầu với nhà thuốc đầu tiên')).toBeVisible();
    await page.getByRole('button', { name: 'Thiết lập nhà thuốc', exact: true }).click();
    await page.getByRole('textbox', { name: /Tên chuỗi/ }).fill('Chuỗi kiểm thử HTTP');
    await page.getByRole('textbox', { name: /Tên nhà thuốc/ }).fill('Nhà thuốc kiểm thử HTTP');
    await page.getByRole('textbox', { name: /Mã nhà thuốc/ }).fill('HTTP-UAT');
    await page.getByRole('dialog', { name: 'Thiết lập nhà thuốc', exact: true }).getByRole('button', { name: 'Tạo nhà thuốc', exact: true }).click();
    await expect(page.getByText('Bắt đầu với nhà thuốc đầu tiên')).toHaveCount(0);
    const bootstrapResponse = await page.request.get('/admin/api/pharmacy/bootstrap');
    expect(bootstrapResponse.status()).toBe(200);
    const bootstrap = (await bootstrapResponse.json()).data;
    expect(bootstrap.current_website).toBeNull();
    const pharmacy = bootstrap.current_pharmacy;
    expect(pharmacy.id).toBeTruthy();
    const command = async (action, values = {}, expected = 200) => {
        const token = await page.locator('meta[name="csrf-token"]').getAttribute('content');
        const response = await page.request.post('/admin/api/pharmacy/commands', { headers: { 'X-CSRF-TOKEN': token, Accept: 'application/json', 'Idempotency-Key': `http-uat:${globalThis.crypto.randomUUID()}` }, data: { action, pharmacy_id: pharmacy.id, ...values } });
        const body = await response.json();
        expect(response.status(), JSON.stringify(body)).toBe(expected);
        return body.data;
    };
    const credentialData = { admin_id: 1, license_number: 'SYNTHETIC-UAT-ONLY', abilities: ['review', 'dispense', 'handover'], valid_from: '2026-01-01', valid_until: '2030-01-01', reason: 'Hồ sơ tổng hợp chỉ dùng kiểm thử' };
    const credential = await command('credential.save', credentialData);
    const product = await command('product.save', { name: 'Hàng thử nghiệm OTC', code: 'HTTP-OTC', base_unit: 'vien', ingredients: 'Dữ liệu tổng hợp', price_minor: '5000', requires_prescription: false });
    const receipt = await command('receipt.create', { product_id: product.id, quantity: '20', unit_cost: '1000', batch_code: 'LOT-HTTP-UAT', expires_at: '2030-01-01', reference: 'HTTP-UAT-RECEIPT' });
    await command('receipt.inspect', { receipt_id: receipt.id, expected_version: receipt.version, decision: 'release', reason: 'Kiểm nhận dữ liệu tổng hợp' });
    const shift = await command('shift.open', { counter_id: bootstrap.counters[0].id, opening_minor: '0' });
    await page.goto('/admin/modules/pharmacy/pos');
    await page.getByRole('button', { name: /HTTP-OTC Hàng thử nghiệm OTC/ }).click();
    await page.getByRole('button', { name: 'Lưu hồ sơ & chuẩn bị hàng' }).click();
    await expect(page).toHaveURL(/\/dispensings\/[a-f0-9-]+/);
    const dispensingId = page.url().split('/').pop();
    await page.getByRole('button', { name: '1. Chuẩn bị hàng & lô' }).click();
    const lot = page.getByRole('combobox', { name: 'Lô thực lấy 1' });
    await lot.focus(); await lot.press('ArrowDown');
    await page.getByText(/LOT-HTTP-UAT.*Khả dụng 20$/).click();
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByRole('button', { name: '2. Kiểm tra chuyên môn' })).toBeEnabled();
    await page.getByRole('button', { name: '2. Kiểm tra chuyên môn' }).click();
    const decision = page.getByRole('combobox', { name: /Kết quả/ });
    await decision.focus(); await decision.press('ArrowDown');
    await page.getByText('Đã kiểm tra — đồng ý', { exact: true }).click();
    await page.getByRole('textbox', { name: /Căn cứ kiểm tra/ }).fill('Đối chiếu bộ dữ liệu tổng hợp UAT');
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await page.getByRole('button', { name: '3. Thu tiền & chốt' }).click();
    const shiftSelector = page.getByRole('combobox', { name: /Ca thu tiền/ });
    await shiftSelector.focus(); await shiftSelector.press('ArrowDown');
    await page.getByText(shift.id, { exact: true }).last().click();
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByText('Đã thu tiền', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '4. Bàn giao' }).click();
    await page.getByRole('textbox', { name: /Người nhận/ }).fill('Người nhận tổng hợp HTTP');
    await page.getByRole('textbox', { name: /Ghi nhận bàn giao/ }).fill('Đã đối chiếu dữ liệu kiểm thử');
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByText('Đã bàn giao', { exact: true }).first()).toBeVisible();
    await page.getByRole('button', { name: 'Yêu cầu bản in' }).click();
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    const popupPromise = page.waitForEvent('popup');
    await page.getByRole('link', { name: 'Mở bản in' }).click();
    const printed = await popupPromise; await printed.waitForLoadState();
    await expect(printed.locator('body')).toContainText('Hàng thử nghiệm OTC');
    await printed.close();
    await page.getByRole('button', { name: 'Đóng', exact: true }).click();
    await expect(page.locator('.ant-message-notice')).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('pharmacy-native-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByText('Đã bàn giao', { exact: true }).first()).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath('pharmacy-native-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1280, height: 900 });
    const secondPharmacy = await command('pharmacy.create', { chain_id: bootstrap.chains[0].id, name: 'Z Nhà thuốc kiểm thử B', code: 'HTTP-B' });
    await page.goto('/admin/modules/pharmacy/pos');
    await page.getByRole('button', { name: /HTTP-OTC Hàng thử nghiệm OTC/ }).click();
    await page.getByRole('button', { name: 'Đổi nhà thuốc đang làm việc' }).click();
    await page.getByRole('button', { name: 'Chuyển sang Z Nhà thuốc kiểm thử B', exact: true }).click();
    await page.getByRole('button', { name: 'Bỏ bản nháp và chuyển' }).click();
    await expect(page.getByRole('button', { name: 'Lưu hồ sơ & chuẩn bị hàng' })).toBeDisabled();
    const selectedBootstrap = (await (await page.request.get(`/admin/api/pharmacy/bootstrap?pharmacy_id=${secondPharmacy.id}`)).json()).data;
    expect(selectedBootstrap.current_pharmacy.id).toBe(secondPharmacy.id);
    await page.goto('/admin/modules/pharmacy/shifts');
    await page.getByRole('button', { name: 'Đóng ca', exact: true }).click();
    await page.getByRole('spinbutton', { name: /Tiền mặt thực đếm/ }).fill('5000');
    await page.getByRole('textbox', { name: /Lý do/ }).fill('Kiểm đếm dữ liệu UAT');
    await page.getByRole('button', { name: 'Lưu và xác nhận' }).click();
    await expect(page.getByText('Đã đóng', { exact: true }).first()).toBeVisible();
    await command('credential.save', { ...credentialData, credential_id: credential.id, expected_version: credential.version, status: 'inactive' });
    await command('dispensing.review', { dispensing_id: dispensingId, expected_version: 5, decision: 'approved', reason: 'Không được vượt điều kiện chuyên môn đã thu hồi' }, 403);
    await command('membership.save', { admin_id: fixture.reader.id, permissions: ['pharmacy.view', 'pharmacy.report.view'], chain_wide: false });
    const readerContext = await browser.newContext({ baseURL: 'http://127.0.0.1:8131' });
    const reader = await readerContext.newPage(); const readerRequests = [];
    reader.on('request', (request) => readerRequests.push(request.url()));
    await reader.goto('/admin/pharmacy/login');
    await reader.getByLabel('Tên đăng nhập hoặc email').fill(fixture.reader.username);
    await reader.getByLabel('Mật khẩu', { exact: true }).fill(fixture.reader.password);
    await reader.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await expect(reader.getByRole('heading', { name: 'Báo cáo', exact: true })).toBeVisible();
    expect(readerRequests.some((url) => /\/admin\/api\/pharmacy\/(?:dispensings|patients|prescriptions)/.test(url))).toBe(false);
    expect((await reader.request.get(`/admin/api/pharmacy/patients?pharmacy_id=${pharmacy.id}`)).status()).toBe(403);
    await readerContext.close();
    const storage = await page.evaluate(() => JSON.stringify(localStorage));
    expect(storage).not.toContain('Người nhận tổng hợp HTTP');
    expect(websiteHeaders.every((value) => value === undefined)).toBe(true);
    expect(errors).toEqual([]);
});
