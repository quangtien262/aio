    await page.goto('/admin/modules/manufacturing/execution');
    await expect(page.getByRole('heading', { name: 'Điều hành phân xưởng', exact: true })).toBeVisible();
    await expect(page.getByText('Website mặc định', { exact: true })).toBeHidden();
    await expect(page.getByRole('button', { name: 'Website', exact: true })).toBeHidden();
    await page.reload();
    await expect(page.getByRole('heading', { name: 'Điều hành phân xưởng', exact: true })).toBeVisible();
    await page.locator('.ant-select[aria-label="Nhà máy sản xuất"]').click();
